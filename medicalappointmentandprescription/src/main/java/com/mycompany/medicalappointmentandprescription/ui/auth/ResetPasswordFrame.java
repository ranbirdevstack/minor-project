    private void btnresetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnresetActionPerformed
        String newPass=new String(txtnewpass.getPassword());
        String conPass = new String(txtconpass.getPassword());
        if(newPass.isEmpty()||conPass.isEmpty())
        {
            JOptionPane.showMessageDialog(this, "Please enter fill Password");
            return;
        }
        if(newPass.length()<6)
        {
            JOptionPane.showMessageDialog(this, "Password at least contain 6 character");
            return;
        }
        if(!newPass.equals(conPass))
        {
            JOptionPane.showMessageDialog(this, "Password do not match", "Password Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        UserDao us=new UserDao();
        boolean update=us.updatePassword(verfiedUserId, newPass);
        if(update)
        {
         JOptionPane.showMessageDialog(this, "Password reset successfully"); 
         LoginFrame lo = new LoginFrame();
         lo.setLocationRelativeTo(null);
         lo.setVisible(true);
         this.dispose();
        }
        else 
        {
          JOptionPane.showMessageDialog(this, "User not Found Password couldn't reset", "Error", JOptionPane.ERROR_MESSAGE);
        }
        
    }//GEN-LAST:event_btnresetActionPerformed

