    private void btnaddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnaddActionPerformed
      String doctorName=txtdocname.getText().trim();
       String username=txtusername.getText().trim();
       String password=new String(txtpassword.getPassword()).trim();
       String contact=txtcontactnumber.getText();
       String specialization=cmbspecialization.getSelectedItem().toString();
       String feestxt=txtconsultationfee.getText();
       String startTime=txtstarthours.getText();
       String endTime=txtendhours.getText();
       if(doctorName.isEmpty()||username.isEmpty()||password.isEmpty()||contact.isEmpty()||specialization.isEmpty()||feestxt.isEmpty()||startTime.isEmpty()||endTime.isEmpty())
       {
           JOptionPane.showMessageDialog(this, "Please fill in all required feild", "Validation Error", JOptionPane.WARNING_MESSAGE);
           return;
       }
       if(!contact.matches("[0-9]{10}"))
       {
           JOptionPane.showMessageDialog(this, "Contact must contain exactly 10 digits.", "Validation Error", JOptionPane.WARNING_MESSAGE);
           return;
       }
       if(!username.matches("[a-zA-Z0-9_.]{4,30}"))
       {
           JOptionPane.showMessageDialog(this, "Username letter contains 4-30 characters & use letters, number,Underscore or dot", "Validation Error", JOptionPane.WARNING_MESSAGE);
           return;
       }
       if(password.length()<6)
        {
            JOptionPane.showMessageDialog(this, "Password at least contain 6 character", "Validation Error",JOptionPane.WARNING_MESSAGE);
            return;
        }
       if(ud.findByUsername(username)!=null)
       {
           JOptionPane.showMessageDialog(this, "This username already exist", "Duplicate Error", JOptionPane.WARNING_MESSAGE);
           return;
       }
       double fee;
       try
       {
           fee=Double.parseDouble(feestxt);
           if(!Double.isFinite(fee)||fee <=0)
           {
               throw new NumberFormatException();
           }
       }
       catch(NumberFormatException e)
       {
           JOptionPane.showMessageDialog(this, " Enter a valid consultatin fee greater than zero.", "Validation Error", JOptionPane.WARNING_MESSAGE);
           return; 
       }
         DateTimeFormatter time=DateTimeFormatter.ofPattern("hh:mm a").withLocale(java.util.Locale.ENGLISH);
        LocalTime start,end;
        start=LocalTime.parse(startTime.toUpperCase(),time);
        end=LocalTime.parse(endTime.toUpperCase(),time);
       try
       {
      
        if(!start.isBefore(end))
        {
         JOptionPane.showMessageDialog(this, " End time muust be later than start time.", "Validation Error", JOptionPane.WARNING_MESSAGE);
           return;    
        }
       }
       catch(DateTimeParseException e)
       {
        JOptionPane.showMessageDialog(this, " Enter time in a format 09:00 AM or 02:00PM", "Invalid working hours", JOptionPane.WARNING_MESSAGE);
           return;     
       }
       List<DayOfWeek> workingdays=new ArrayList<>();
       if(chkmon.isSelected())
           workingdays.add(DayOfWeek.MONDAY);
       if(chktue.isSelected())
           workingdays.add(DayOfWeek.TUESDAY);
       if(chkwed.isSelected())
           workingdays.add(DayOfWeek.WEDNESDAY);
       if(chkthu.isSelected())
           workingdays.add(DayOfWeek.THURSDAY);
       if(chkfri.isSelected())
           workingdays.add(DayOfWeek.FRIDAY);
       if(chksat.isSelected())
           workingdays.add(DayOfWeek.SATURDAY);
       if(chksun.isSelected())
           workingdays.add(DayOfWeek.SUNDAY);
       if(workingdays.isEmpty())
       {
           JOptionPane.showMessageDialog(this, "Please at least select one working day.", "Validation Error", JOptionPane.WARNING_MESSAGE);
           return;
       }
       boolean available = false;
       if(rbnavailable.isSelected())
           available=true;
       if(rbnunavailable.isSelected())
           available=false;
       else
           JOptionPane.showMessageDialog(this, "Please select availabilty status");
       User u= new User(0,username,doctorName,contact,"Doctor",password,true,available);
       if(!ud.addUser(u))
       {
           JOptionPane.showMessageDialog(this, "Unable to create user account.", "Error", JOptionPane.ERROR_MESSAGE);
           return;
       }
       String workinghours = start.format(time)+" - "+end.format(time);
       Doctor d=new Doctor(0,u.getUserId(),doctorName,specialization,contact,fee,workinghours,workingdays,available);
           if(!dd.addDoctor(d))
           {
               ud.deleteAccount(u.getUserId());
               JOptionPane.showMessageDialog(this, "Doctor profile could not created and account creation is rolled back.", "Error", JOptionPane.ERROR_MESSAGE);
           return;
           }
           JOptionPane.showMessageDialog(this,"Doctor succesfuly added!\n\n"+"Doctor Id : "+d.getDoctorId()+"\n Doctor Name :"+d.getDoctorName(),"Success",JOptionPane.INFORMATION_MESSAGE);
           clearForm();
    }//GEN-LAST:event_btnaddActionPerformed
