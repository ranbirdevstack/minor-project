    private void btnregisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnregisterActionPerformed
        String patientName = txtpatientname.getText().trim();
        String ageText = txtage.getText().trim();
        String contact = txtcontactnumber.getText().trim();
        String address = txtaddress.getText().trim();

        if (patientName.isEmpty() || ageText.isEmpty()|| contact.isEmpty() || address.isEmpty()|| cmbgender.getSelectedIndex() == 0|| cmbbloodgroup.getSelectedIndex() == 0) {

            JOptionPane.showMessageDialog(this,
                    "Please fill all the fields.",
                    "Validation Error",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!patientName.matches("[a-zA-Z ]+")) {

            JOptionPane.showMessageDialog(this,
                    "Patient name should contain only letters.",
                    "Invalid Name",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        int age;

        try {
            age = Integer.parseInt(ageText);

            if (age <= 0 || age > 120) {
                throw new NumberFormatException();
            }

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(this,
                    "Please enter a valid age between 1 and 120.",
                    "Invalid Age",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!contact.matches("[0-9]{10}")) {

            JOptionPane.showMessageDialog(this,
                    "Contact number must contain exactly 10 digits.",
                    "Invalid Contact",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        String gender = cmbgender.getSelectedItem().toString();
        String bloodGroup = cmbbloodgroup.getSelectedItem().toString();

        // Create Patient object
        Patient patient = new Patient(
                0,
                staffId,
                patientName,
                age,
                gender,
                contact,
                address,
                bloodGroup,
                LocalDateTime.now()
        );

        if (pd.registerPatient(patient,staffId)) {

            JOptionPane.showMessageDialog(this,
                    "Patient registered successfully!",
                    "Registration Successful",
                    JOptionPane.INFORMATION_MESSAGE);

        } else {

            JOptionPane.showMessageDialog(this,
                    "Unable to register patient. Please try again.",
                    "Registration Failed",
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnregisterActionPerformed

