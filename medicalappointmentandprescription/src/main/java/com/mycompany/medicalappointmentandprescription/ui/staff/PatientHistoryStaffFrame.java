    private void loadPatientHistory() {

    Patient patient = pd.findByPatientId(patientId);

    if (patient == null) {

        JOptionPane.showMessageDialog(
                this,
                "Patient record not found.",
                "Error",
                JOptionPane.ERROR_MESSAGE
        );

        dispose();
        return;
    }

    lblpatientnamevalue.setText(patient.getFullName());

    lblpatientidvalue.setText(String.valueOf(patient.getPatientId()));

    lblagevalue.setText(String.valueOf(patient.getAge()));

    lblgendervalue.setText(
            patient.getGender()
    );

    List<MedicalHistory> histories = hd.findByPatientId(patientId);

    histories.sort(
            Comparator.comparing(
                    MedicalHistory::getRecordedAt,
                    Comparator.nullsLast(Comparator.reverseOrder())
            )
    );

    DefaultTableModel model = new DefaultTableModel(
            new String[]{"Date", "Doctor Name"}, 0
    ) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };

    String lastUpdated = "N/A";

    for (MedicalHistory history : histories) {

        Doctor doctor = dd.findByDoctorId(history.getDoctorId());

        String doctorName = "Unknown";

        if (doctor != null) {
            doctorName = doctor.getDoctorName();
        }

        String historyDate = "N/A";

        if (history.getRecordedAt() != null) {

            historyDate = history.getRecordedAt()
                    .format(dateFormatter);
        }

        model.addRow(new Object[]{
            historyDate,
            doctorName
        });

        if ("N/A".equals(lastUpdated)
                && !"N/A".equals(historyDate)) {

            lastUpdated = historyDate;
        }
    }

    tblmedicalhistory.setModel(model);

    lblmedicalhistoryvalue.setText(
            String.valueOf(histories.size())
    );

    lbllastupdatedatevalue.setText(lastUpdated);
     btnrefresh.setText("↺ Refresh");
}
    

