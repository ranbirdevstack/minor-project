   private void loadPatientDetails() {

    Patient patient = pd.findByPatientId(patientId);

    if (patient == null) {

        JOptionPane.showMessageDialog(
                this,
                "Patient record not found.",
                "Error",
                JOptionPane.ERROR_MESSAGE
        );

        dispose();
        return;
    }

    lblpatientidvalue.setText( String.valueOf(patient.getPatientId()));

    lblpatientnamevalue.setText(patient.getFullName());

    lblagevalue.setText(String.valueOf(patient.getAge()) );

    lblgendervalue.setText(patient.getGender());

    lblcontactvalue.setText( patient.getContactNumber());

    lbladdressvalue.setText(patient.getAddress());

    lblbloodgroupvalue.setText(patient.getBloodGroup());

    lbllregisteredbyvalue.setText(String.valueOf(patient.getRegisteredBy()));

    DateTimeFormatter formatter =DateTimeFormatter.ofPattern("dd-MM-yyyy HH:mm");

    lbllregistereddatevalue.setText(patient.getRegistrationDate().format(formatter));
    btnrefresh.setText("↺ Refresh");
}
