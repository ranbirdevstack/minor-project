    private void btnverifyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnverifyActionPerformed
       String enteredOtp=txtotp.getText().trim();
       int currentUserId;
        try{
          currentUserId=Integer.parseInt(txtuserid.getText().trim());
      }
      catch(NumberFormatException e){
           JOptionPane.showMessageDialog(this, "Invalid please enter valid value","Invalid User Id",JOptionPane.ERROR_MESSAGE);
           return;
      }
       if(generatedOtp == null)
       {
           JOptionPane.showMessageDialog(this, "Please generate otp first");
           return;
       }
       if(currentUserId!=verfiedUserId)
       {
          JOptionPane.showMessageDialog(this, "User ID changed. Please generate otp first");
           return;  
       }
       if(System.currentTimeMillis()>otpExpireTime)
       {
           generatedOtp=null;
            JOptionPane.showMessageDialog(this, "OTP expied. Please generate a new otp ");
           return;
       }
       if(++otpAttempts>5)
       {
           generatedOtp=null;
            JOptionPane.showMessageDialog(this, "Too many Attemps. Please generate a new otp ");
           return;
       }
       if(!generatedOtp.equals(enteredOtp))
       {
            JOptionPane.showMessageDialog(this, "Invalid OTP. Please try again.");
           return;
       }
       JOptionPane.showMessageDialog(this, "OTP verfied Succefully.");

       generatedOtp=null;
       ResetPasswordFrame fr = new ResetPasswordFrame(verfiedUserId);
       fr.setLocationRelativeTo(null);
       fr.setVisible(true);
       this.dispose();
    }//GEN-LAST:event_btnverifyActionPerformed

    private void btnsendActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsendActionPerformed
       
       int userId;
      try{
          userId=Integer.parseInt(txtuserid.getText().trim());
      }
      catch(NumberFormatException e){
           JOptionPane.showMessageDialog(this, "Invalid please enter valid value","Invalid User Id",JOptionPane.ERROR_MESSAGE);
           return;
      }
      UserDao us = new UserDao();
      User u = us.findByUserId(userId);
      if(u== null)
      {
           JOptionPane.showMessageDialog(this, "Invalid UserId Please enter a registered Id","User Id not found",JOptionPane.ERROR_MESSAGE);
           return;
      }
       generatedOtp=String.format("%06d", sec.nextInt(1_00_000));
       verfiedUserId=userId;
       otpExpireTime=System.currentTimeMillis()+(5*60*1000);
       otpAttempts=0;
       txtotp.setText("");
       JOptionPane.showMessageDialog(this, "Your Otp is :"+generatedOtp+"\n Valid for 5 minutes","OTP Generated",JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnsendActionPerformed

