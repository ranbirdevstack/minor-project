    private void loadStaffDetails() {

        User staff = ud.findByUserId(staffId);

        if (staff == null || !"Staff".equals(staff.getRole())) {

            JOptionPane.showMessageDialog(this,
                    "Staff record not found.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);

            dispose();
            return;
        }

        // Display existing details
        txtstaffname.setText(staff.getFullName());
        txtcontactnumber.setText(staff.getContactNumber());
       if (staff.getAvaliabilityStatus()) {
            rbnavailable.setSelected(true);
        } else {
            rbnunavailable.setSelected(true);
        }
       if (staff.getIsActive()) {
            rbnactive.setSelected(true);
        } else {
            rbndeactive.setSelected(true);
        }
    }
