    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdateActionPerformed
        String staffName = txtstaffname.getText().trim();
        String contact = txtcontactnumber.getText().trim();

       if (staffName.isEmpty() || contact.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Please fill all the required fields.",
                    "Validation Error",
                    JOptionPane.WARNING_MESSAGE);

            return;
        }
       if (!staffName.matches("[a-zA-Z ]+")) {

            JOptionPane.showMessageDialog(this,
                    "Staff name should contain only letters.",
                    "Invalid Name",
                    JOptionPane.WARNING_MESSAGE);

            return;
        }
       if (!contact.matches("[0-9]{10}")) {

            JOptionPane.showMessageDialog(this,
                    "Contact number must contain exactly 10 digits.",
                    "Invalid Contact Number",
                    JOptionPane.WARNING_MESSAGE);

            return;
        }
       if (!rbnavailable.isSelected()
                && !rbnunavailable.isSelected()) {

            JOptionPane.showMessageDialog(this,
                    "Please select availability status.",
                    "Validation Error",
                    JOptionPane.WARNING_MESSAGE);

            return;
        }
        if (!rbnactive.isSelected()
                && !rbndeactive.isSelected()) {

            JOptionPane.showMessageDialog(this,
                    "Please select account status.",
                    "Validation Error",
                    JOptionPane.WARNING_MESSAGE);

            return;
        }
       User staff = ud.findByUserId(staffId);

        if (staff == null || !"Staff".equals(staff.getRole())) {

            JOptionPane.showMessageDialog(this,
                    "Staff account not found.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);

            dispose();
            return;
        }
        staff.setFullName(staffName);
        staff.setContactNumber(contact);
        staff.setAvaliabilityStatus(rbnavailable.isSelected());
        staff.setIsActive(rbnactive.isSelected());
        if (ud.updateUser(staff)) {

            JOptionPane.showMessageDialog(this,
                    "Staff details updated successfully!",
                    "Update Successful",
                    JOptionPane.INFORMATION_MESSAGE);

            dispose();

        } else {

            JOptionPane.showMessageDialog(this,
                    "Unable to update staff details.",
                    "Update Failed",
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnupdateActionPerformed

