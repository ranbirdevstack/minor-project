    private void loadPatientDetails() {

        existingPatient = pd.findByPatientId(patientId);

        if (existingPatient == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "Patient record not found.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );

            dispose();
            return;
        }

        txtpatientname.setText(existingPatient.getFullName());

        txtage.setText(String.valueOf(existingPatient.getAge()));

        cmbgender.setSelectedItem(existingPatient.getGender());

        txtcontactnumber.setText(existingPatient.getContactNumber());

        txtaddress.setText(existingPatient.getAddress());

        cmbbloodgroup.setSelectedItem(existingPatient.getBloodGroup());
    }

