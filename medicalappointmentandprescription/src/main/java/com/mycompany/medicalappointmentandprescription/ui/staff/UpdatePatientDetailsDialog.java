    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdateActionPerformed
       String name = txtpatientname.getText().trim();

    String ageText = txtage.getText().trim();

    String gender = cmbgender.getSelectedItem().toString();

    String contact = txtcontactnumber.getText().trim();

    String address = txtaddress.getText().trim();

    String bloodGroup = cmbbloodgroup.getSelectedItem().toString();


    if (name.isEmpty()) {

        JOptionPane.showMessageDialog(this, "Please enter patient name.");
        txtpatientname.requestFocus();
        return;
    }

    if (!name.matches("[a-zA-Z ]+")) {

        JOptionPane.showMessageDialog(this, "Patient name must contain only letters.");
        txtpatientname.requestFocus();
        return;
    }


    int age;

    try {

        age = Integer.parseInt(ageText);

        if (age <= 0 || age > 120) {
            throw new NumberFormatException();
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this, "Please enter a valid age.");
        txtage.requestFocus();
        return;
    }

    if (gender.equals("Select a Gender")) {

        JOptionPane.showMessageDialog(this, "Please select gender.");
        cmbgender.requestFocus();
        return;
    }

    if (!contact.matches("[0-9]{10}")) {

        JOptionPane.showMessageDialog(
                this,
                "Contact number must contain exactly 10 digits."
        );

        txtcontactnumber.requestFocus();
        return;
    }


    if (address.isEmpty()) {

        JOptionPane.showMessageDialog(this, "Please enter address.");
        txtaddress.requestFocus();
        return;
    }


    if (bloodGroup.equals("Select a Blood Group")) {

        JOptionPane.showMessageDialog(this, "Please select blood group.");
        cmbbloodgroup.requestFocus();
        return;
    }


    // Update existing patient object
    existingPatient.setFullName(name);

    existingPatient.setAge(age);

    existingPatient.setGender(gender);

    existingPatient.setContactNumber(contact);

    existingPatient.setAddress(address);

    existingPatient.setBloodGroup(bloodGroup);


    // Save changes through PatientDao
    boolean updated = pd.updatePatient(existingPatient);


    if (updated) {

        JOptionPane.showMessageDialog(
                this,
                "Patient details updated successfully!",
                "Success",
                JOptionPane.INFORMATION_MESSAGE
        );

        dispose();

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Unable to update patient details.",
                "Update Failed",
                JOptionPane.ERROR_MESSAGE
        );
    }

    }//GEN-LAST:event_btnupdateActionPerformed

