  private void loadDoctors()
  {
      String[]columns={"Doctor Id","Doctor Name","Specialization","Contact","Availabilty","Action"};
      tabelMode=new DefaultTableModel(columns,0){
      
      @Override
      public boolean isCellEditable(int row,int column)
      {
          return column==5;
      }
      };
      for(Doctor d:dd.findAll())
      {
          tabelMode.addRow(new Object[]{d.getDoctorId(),d.getDoctorName(),d.getSpecialization(),d.getContactNumber(),d.getAvaliabilityStatus()?"Available":"Unavailable","View Details"});
      }
      tbldoctors.setModel(tabelMode);
      tbldoctors.getColumnModel().getColumn(5).setCellRenderer(new ButtonRenderer());
      tbldoctors.getColumnModel().getColumn(5).setCellEditor(new ButtonEditor(new JCheckBox(),tbldoctors));
      btnrefresh.setText("↺ Refresh");
  }
  private void searchDoctor()
  {
      String key=txtsearch.getText().trim().toLowerCase();
      tabelMode.setRowCount(0);
      for(Doctor d:dd.findAll())
      {
          boolean matchId=String.valueOf(d.getDoctorId()).contains(key);
          boolean matchName=d.getDoctorName().toLowerCase().contains(key);
          if(matchId||matchName)
             tabelMode.addRow(new Object[]{d.getDoctorId(),d.getDoctorName(),d.getSpecialization(),d.getContactNumber(),d.getAvaliabilityStatus()?"Available":"Unavailable","View Details"});
      }
      if(tabelMode.getRowCount()==0)
      JOptionPane.showMessageDialog(this, "No Doctor Found ", "Search Result", JOptionPane.INFORMATION_MESSAGE);
  }
