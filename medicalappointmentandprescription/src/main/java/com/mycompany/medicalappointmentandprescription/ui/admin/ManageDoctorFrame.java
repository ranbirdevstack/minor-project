    private class ButtonRenderer extends JButton implements javax.swing.table.TableCellRenderer
    {
        public  ButtonRenderer ()
        {
            setText("View Details");
            setOpaque(true);
        }
        @Override
        public Component getTableCellRendererComponent(JTable table,Object value,boolean isSelected,boolean hasFocused,int row,int column)
        {
            setText("View Details");
            return this;
        }
    }
    private class ButtonEditor extends DefaultCellEditor
    {
       private final JButton button;
       private final JTable table;
       private int selectedRow;
       public ButtonEditor(JCheckBox checkbox,JTable table)
       {
           super(checkbox);
           this.table=table;
           this.button=new JButton("View Details");
           button.addActionListener(e->{
               fireEditingStopped();
              int row=table.convertRowIndexToModel(selectedRow);
              int doctorId=(int)table.getModel().getValueAt(row, 0);
           DoctorDetailsFrame fr=new DoctorDetailsFrame(doctorId);
           fr.setLocationRelativeTo(null);
           fr.setVisible(true);
           
       });
           
       }
        @Override
        public Component getTableCellEditorComponent(JTable table,Object value,boolean isSelected,int row,int column)
        {
          selectedRow=row;
          return button;
        }
        
        @Override
        public Object getCellEditorValue()
        {
            return "View Details";
        }
    }

