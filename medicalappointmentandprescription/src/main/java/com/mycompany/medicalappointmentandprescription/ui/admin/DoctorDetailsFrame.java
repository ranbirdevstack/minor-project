    public void loadDoctorDetails()
    {
        Doctor d=dd.findByDoctorId(doctorId);
        if(d==null)
        {
           JOptionPane.showMessageDialog(this, "Doctor not Found", "Error", JOptionPane.ERROR_MESSAGE);
           return ;
        }
        User u=ud.findByUserId(d.getUserId());
        lbldoctoridvalue.setText(String.valueOf(d.getDoctorId()));
        lbldoctornamevalue.setText(d.getDoctorName());  
        lblcontactvalue.setText(d.getContactNumber());
        lblspecializationvalue.setText(d.getSpecialization());
        lblfeevalue.setText(String.format(java.util.Locale.ENGLISH,"₹%.2f",d.getConsultationFee()));
        lblworkinghourvalue.setText(d.getWorkingHours());
        String days = d.getWorkingDays() == null ? "Not Specified" : ((java.util.Collection<?>) d.getWorkingDays()).stream().map(Object::toString).collect(java.util.stream.Collectors.joining(", "));
        lblworkingdayvalue.setText("<html>" + days.replace(", ", ",<br>") + "</html>");
        lblavailabiltyvalue.setText(d.getAvaliabilityStatus()?"Available":"Unavailable");
        lblusernamevalue.setText(u==null?"Not Found":u.getUsername());
        btnrefresh.setText("↺ Refresh");
    }

