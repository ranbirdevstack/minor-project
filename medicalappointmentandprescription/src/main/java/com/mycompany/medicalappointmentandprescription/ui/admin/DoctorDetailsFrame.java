    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
        int choice= JOptionPane.showConfirmDialog(this, "Are you sure to delete this doctor?", "Confirm Delete",JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if(choice != JOptionPane.YES_OPTION)
            return;
        boolean deleted=dd.deleteDoctor(doctorId);
        if(deleted)
        {
            JOptionPane.showMessageDialog(this, "Deleted Succesfully");
            dispose();
        }
        else
        {
            JOptionPane.showMessageDialog(this, "Doctor could not deleted may have link to appointment,prescription, or medical history", "Deletion falied",JOptionPane.WARNING_MESSAGE); 
        }
    }//GEN-LAST:event_btndeleteActionPerformed

    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdateActionPerformed
       Doctor d=dd.findByDoctorId(doctorId);
       if(d==null)
       {
         JOptionPane.showMessageDialog(this, "Doctor not Found");
           return ;  
       }
       UpdateDoctorDetailDialog fr=new UpdateDoctorDetailDialog(this,true,doctorId);
       fr.setLocationRelativeTo(this);
       fr.setVisible(true);
       loadDoctorDetails();
        btnrefresh.setText("↺ Refresh");
    }//GEN-LAST:event_btnupdateActionPerformed

    private void btnrefreshActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnrefreshActionPerformed
        btnrefresh.setText("\u27F3 Refreshing ");
          btnrefresh.setEnabled(false);
          SwingWorker<Void,Void> worker=new SwingWorker<>(){
            @Override
            public Void doInBackground()throws Exception
            {
                Thread.sleep(300);
                return null;
            }
             @Override
            public void done()
            {
              try
              {
                  
                  loadDoctorDetails();
              }
              finally
              {
                  btnrefresh.setText("↺ Refresh");
                  btnrefresh.setEnabled(true);
              }
            }
          };
          worker.execute();
    }//GEN-LAST:event_btnrefreshActionPerformed

