    private class ExportButtonRenderer extends JButton
        implements TableCellRenderer {

    public ExportButtonRenderer() {
        setText("Export PDF");
        setOpaque(true);
    }

    @Override
    public Component getTableCellRendererComponent(
            JTable table, Object value,
            boolean isSelected, boolean hasFocus,
            int row, int column) {

        setText("Export PDF");
        return this;
    }
}
    private class ExportButtonEditor extends AbstractCellEditor
        implements TableCellEditor {

    private final JButton button = new JButton("Export PDF");

    private int prescriptionId;

    public ExportButtonEditor() {

        button.addActionListener(e -> {

            fireEditingStopped();

            exportPrescriptionPDF(prescriptionId);
        });
    }

    @Override
    public Component getTableCellEditorComponent(
            JTable table, Object value,
            boolean isSelected, int row, int column) {

        prescriptionId = Integer.parseInt(
                table.getValueAt(row, 0).toString());

        return button;
    }

    @Override
    public Object getCellEditorValue() {
        return "Export PDF";
    }
}
    

