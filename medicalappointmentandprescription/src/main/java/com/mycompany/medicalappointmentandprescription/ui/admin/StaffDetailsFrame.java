    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
        int choice = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this staff account?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE
    );

    if (choice == JOptionPane.YES_OPTION) {

        if (ud.deleteAccount(staffId)) {

            JOptionPane.showMessageDialog(this,
                    "Staff account deleted successfully!",
                    "Success",
                    JOptionPane.INFORMATION_MESSAGE);

            ManageStaffFrame frame = new ManageStaffFrame();
            frame.setLocationRelativeTo(null);
            frame.setVisible(true);

            this.dispose();

        } else {

            JOptionPane.showMessageDialog(this,
                    "Unable to delete staff account.\n"
                    + "This staff member may be linked to registered records.",
                    "Delete Failed",
                    JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_btndeleteActionPerformed

