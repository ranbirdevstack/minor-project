    private void loadStaffDetails() {

    User staff = ud.findByUserId(staffId);

    if (staff == null || !"Staff".equals(staff.getRole())) {

        JOptionPane.showMessageDialog(this,
                "Staff record not found.",
                "Error",
                JOptionPane.ERROR_MESSAGE);

        this.dispose();
        return;
    }
     lblstaffidvalue.setText(String.valueOf(staff.getUserId()));
     lblstaffnamevalue.setText(staff.getFullName());
     lblusernamevalue.setText(staff.getUsername());
     lblcontactvalue.setText(staff.getContactNumber());
     lblavailabiltyvalue.setText(
            staff.getAvaliabilityStatus() ? "Available" : "Unavailable"
    );
}


