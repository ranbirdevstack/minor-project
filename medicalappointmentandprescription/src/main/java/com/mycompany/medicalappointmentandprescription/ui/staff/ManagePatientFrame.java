    private class ButtonRenderer extends JButton
        implements TableCellRenderer {

    public ButtonRenderer() {
        setOpaque(true);
    }

    @Override
    public Component getTableCellRendererComponent(
            JTable table,
            Object value,
            boolean isSelected,
            boolean hasFocus,
            int row,
            int column) {

        setText(value == null ? "" : value.toString());

        return this;
    }
}
    private class ButtonEditor extends DefaultCellEditor {

    private final JButton button;
    private final JTable table;
    private final int actionColumn;
    private int selectedRow;

    public ButtonEditor(JCheckBox checkbox,
                        JTable table,
                        int actionColumn) {

        super(checkbox);

        this.table = table;
        this.actionColumn = actionColumn;

        button = new JButton();

        button.addActionListener(e -> {

            fireEditingStopped();

            int row = table.convertRowIndexToModel(selectedRow);

            int patientId = (int) table.getModel()
                    .getValueAt(row, 0);

            if (actionColumn == 6) {

                PatientDetailsFrame fr =new PatientDetailsFrame(patientId);

                fr.setLocationRelativeTo(null);
                fr.setVisible(true);

            } else if (actionColumn == 7) {

                PatientHistoryStaffFrame fr =new PatientHistoryStaffFrame(patientId);

                fr.setLocationRelativeTo(null);
                fr.setVisible(true);
            }
        });
    }

    @Override
    public Component getTableCellEditorComponent(
            JTable table,
            Object value,
            boolean isSelected,
            int row,
            int column) {

        selectedRow = row;

        button.setText(value == null ? "" : value.toString());

        return button;
    }

    @Override
    public Object getCellEditorValue() {

        return button.getText();
    }
}
    

