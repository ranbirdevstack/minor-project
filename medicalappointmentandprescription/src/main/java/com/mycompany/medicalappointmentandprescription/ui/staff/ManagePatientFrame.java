     private void loadPatients() {

    String[] columns = {
        "Patient ID",
        "Patient Name",
        "Age",
        "Gender",
        "Contact Number",
        "Blood Group",
        "Action",
        "Med his"
    };

    tableModel = new DefaultTableModel(columns, 0) {

        @Override
        public boolean isCellEditable(int row, int column) {
            return column == 6 || column == 7;
        }
    };

    for (Patient p : pd.findAll()) {

        tableModel.addRow(new Object[]{
            p.getPatientId(),
            p.getFullName(),
            p.getAge(),
            p.getGender(),
            p.getContactNumber(),
            p.getBloodGroup(),
             "View Details",
             "Med History"
        });
    }

    tblpatient.setModel(tableModel);
    btnrefresh.setText("↺ Refresh");

    tblpatient.getColumnModel().getColumn(6)
            .setCellRenderer(new ButtonRenderer());

    tblpatient.getColumnModel().getColumn(6)
            .setCellEditor(new ButtonEditor(new JCheckBox(), tblpatient, 6));

    tblpatient.getColumnModel().getColumn(7)
            .setCellRenderer(new ButtonRenderer());

    tblpatient.getColumnModel().getColumn(7)
            .setCellEditor(new ButtonEditor(new JCheckBox(), tblpatient, 7));
}
     private void searchPatient() {

    String key = txtsearch.getText().trim().toLowerCase();

    if (key.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Please enter Patient ID, Name or Contact Number.",
                "Search Patient",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    tableModel.setRowCount(0);

    for (Patient p : pd.findAll()) {

        boolean matchId =
                String.valueOf(p.getPatientId()).contains(key);

        boolean matchName =
                p.getFullName().toLowerCase().contains(key);

        boolean matchContact =
                p.getContactNumber().contains(key);

        if (matchId || matchName || matchContact) {

            tableModel.addRow(new Object[]{
                p.getPatientId(),
                p.getFullName(),
                p.getAge(),
                p.getGender(),
                p.getContactNumber(),
                p.getBloodGroup(),
                "View Details",
                "Med History"
            });
        }
    }

    if (tableModel.getRowCount() == 0) {

        JOptionPane.showMessageDialog(
                this,
                "No Patient Found.",
                "Search Result",
                JOptionPane.INFORMATION_MESSAGE
        );
    }
}
