    private void loadStaff() {

    String[] columns = {
        "Staff Id",
        "Staff Name",
        "Contact",
        "Availability",
        "Action"
    };

    tabelMode = new DefaultTableModel(columns, 0) {

        @Override
        public boolean isCellEditable(int row, int column) {
            return column == 4;
        }
    };

    for (User u : ud.findStaffAccount()) {

        tabelMode.addRow(new Object[]{
            u.getUserId(),
            u.getFullName(),
            u.getContactNumber(),
            u.getAvaliabilityStatus()? "Available" : "Unavailable",
            "View Details"
        });
    }

    tblstaffs.setModel(tabelMode);

    tblstaffs.setRowHeight(25);

    tblstaffs.getColumnModel()
            .getColumn(4)
            .setCellRenderer(new ButtonRenderer());

    tblstaffs.getColumnModel()
            .getColumn(4)
            .setCellEditor(
                    new ButtonEditor(new JCheckBox(), tblstaffs)
            );

    btnrefresh.setText("↺ Refresh");
}
    private void searchStaff() {

    String key = txtsearch.getText().trim().toLowerCase();

    tabelMode.setRowCount(0);

    for (User u : ud.findStaffAccount()) {

        boolean matchId =
                String.valueOf(u.getUserId()).contains(key);

        boolean matchName =
                u.getFullName().toLowerCase().contains(key);

        if (matchId || matchName) {

            tabelMode.addRow(new Object[]{
                u.getUserId(),
                u.getFullName(),
                u.getContactNumber(),
                u.getAvaliabilityStatus()? "Available" : "Unavailable",
                "View Details"
            });
        }
    }

    if (tabelMode.getRowCount() == 0) {

        JOptionPane.showMessageDialog(
                this,
                "No Staff Found",
                "Search Result",
                JOptionPane.INFORMATION_MESSAGE
        );
    }
}
