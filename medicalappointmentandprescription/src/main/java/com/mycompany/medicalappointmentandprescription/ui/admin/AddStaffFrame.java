    private void btnaddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnaddActionPerformed
        String staffName = txtstaffname.getText().trim();
        String username = txtusername.getText().trim();
        String contact = txtcontactnumber.getText().trim();

        char[] passwordChars = txtpassword.getPassword();
        String password = new String(passwordChars);

        if (staffName.isEmpty() || username.isEmpty()
                || contact.isEmpty() || password.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Please fill all the fields.",
                    "Validation Error",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!staffName.matches("[a-zA-Z ]+")) {

            JOptionPane.showMessageDialog(this,
                    "Staff name should contain only letters.",
                    "Invalid Name",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (username.length() < 3) {

            JOptionPane.showMessageDialog(this,
                    "Username must contain at least 3 characters.",
                    "Invalid Username",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (ud.findByUsername(username) != null) {

            JOptionPane.showMessageDialog(this,
                    "This username already exists. Please choose another.",
                    "Duplicate Username",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!contact.matches("[0-9]{10}")) {

            JOptionPane.showMessageDialog(this,
                    "Contact number must contain exactly 10 digits.",
                    "Invalid Contact Number",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (password.length() < 6) {

            JOptionPane.showMessageDialog(this,
                    "Password must contain at least 6 characters.",
                    "Invalid Password",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!rbnavailable.isSelected()
                && !rbnunavailable.isSelected()) {

            JOptionPane.showMessageDialog(this,
                    "Please select staff availability.",
                    "Validation Error",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        boolean availabilityStatus = rbnavailable.isSelected();

        User staff = new User(
                0,
                username,
                staffName,
                contact,
                "Staff",
                password,
                true,
                availabilityStatus
        );

        if (ud.addStaff(staff)) {

            JOptionPane.showMessageDialog(this,
                    "Staff registered successfully!",
                    "Success",
                    JOptionPane.INFORMATION_MESSAGE);

            clearFields();

        } else {

            JOptionPane.showMessageDialog(this,
                    "Unable to register staff. Please try again.",
                    "Registration Failed",
                    JOptionPane.ERROR_MESSAGE);
        }

        Arrays.fill(passwordChars, '\0');
    }//GEN-LAST:event_btnaddActionPerformed

