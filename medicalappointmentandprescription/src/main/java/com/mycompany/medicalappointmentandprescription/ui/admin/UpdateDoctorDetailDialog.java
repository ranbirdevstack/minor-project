    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdateActionPerformed
        String name = txtdocname.getText().trim();
        String contact = txtcontactnumber.getText().trim();
        String specialization =
                cmbspecialization.getSelectedItem() == null
                ? ""
                : cmbspecialization.getSelectedItem().toString().trim();

        if (name.isEmpty() || contact.isEmpty()
                || specialization.isEmpty()
                || txtconsultationfee.getText().trim().isEmpty()
                || txtstarthours.getText().trim().isEmpty()
                || txtendhours.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(
                    this, "Please fill in all required fields.");
            return;
        }

        if (!contact.matches("[0-9]{10}")) {
            JOptionPane.showMessageDialog(
                    this, "Contact number must contain exactly 10 digits.");
            return;
        }

        double fee;
        LocalTime startTime;
        LocalTime endTime;

        try {
            fee = Double.parseDouble(
                    txtconsultationfee.getText().trim());

            if (!Double.isFinite(fee) || fee <= 0) {
                JOptionPane.showMessageDialog(
                        this, "Consultation fee must be greater than zero.");
                return;
            }

            startTime = LocalTime.parse(
                    txtstarthours.getText().trim(), timeFormatter);

            endTime = LocalTime.parse(
                    txtendhours.getText().trim(), timeFormatter);

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(
                    this, "Enter a valid consultation fee.");
            return;

        } catch (DateTimeParseException ex) {
            JOptionPane.showMessageDialog(
                    this,
                    "Enter time in the format 09:00 AM or 02:00 PM.");
            return;
        }

        if (!endTime.isAfter(startTime)) {
            JOptionPane.showMessageDialog(
                    this, "End time must be later than start time.");
            return;
        }

        List<DayOfWeek> workingDays = new ArrayList<>();

        if (chkmon.isSelected()) {
            workingDays.add(DayOfWeek.MONDAY);
        }
        if (chktue.isSelected()) {
            workingDays.add(DayOfWeek.TUESDAY);
        }
        if (chkwed.isSelected()) {
            workingDays.add(DayOfWeek.WEDNESDAY);
        }
        if (chkthu.isSelected()) {
            workingDays.add(DayOfWeek.THURSDAY);
        }
        if (chkfri.isSelected()) {
            workingDays.add(DayOfWeek.FRIDAY);
        }
        if (chksat.isSelected()) {
            workingDays.add(DayOfWeek.SATURDAY);
        }
        if (chksun.isSelected()) {
            workingDays.add(DayOfWeek.SUNDAY);
        }

        if (workingDays.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this, "Select at least one working day.");
            return;
        }

        boolean available = rbnavailable.isSelected();
        boolean active=rbnactive.isSelected();

        if (!available && !rbnunavailable.isSelected()) {
            JOptionPane.showMessageDialog(
                    this, "Select the doctor's availability status.");
            return;
        }
        
        if (!active && !rbndeactive.isSelected()) {
            JOptionPane.showMessageDialog(
                    this, "Select the doctor's account is active or not.");
            return;
        }
        String workingHours =
                startTime.format(timeFormatter)
                + " - "
                + endTime.format(timeFormatter);

        Doctor updatedDoctor = new Doctor(
                oldDoctor.getDoctorId(),
                oldDoctor.getUserId(),
                name,
                specialization,
                contact,
                fee,
                workingHours,
                workingDays,
                available
        );

        // Update doctor details first.
        boolean doctorUpdated =
                dd.updateDoctor(updatedDoctor);

        if (!doctorUpdated) {
            JOptionPane.showMessageDialog(
                    this,
                    "Unable to update doctor details.",
                    "Update Failed",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        // Keep the linked user account's name and contact synchronized.
        linkedUser.setFullName(name);
        linkedUser.setContactNumber(contact);
        linkedUser.setIsActive(active);
        linkedUser.setAvaliabilityStatus(available);

        boolean userUpdated = ud.updateUser(linkedUser);

        if (!userUpdated) {
            JOptionPane.showMessageDialog(
                    this,
                    "Doctor details were updated, but linked user details "
                    + "could not be updated. Please check UserDao.",
                    "Partial Update",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        JOptionPane.showMessageDialog(
                this,
                "Doctor details updated successfully!",
                "Success",
                JOptionPane.INFORMATION_MESSAGE
        );

        dispose();
    }//GEN-LAST:event_btnupdateActionPerformed

