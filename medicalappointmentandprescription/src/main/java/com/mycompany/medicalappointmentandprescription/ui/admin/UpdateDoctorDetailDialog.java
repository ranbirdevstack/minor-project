        private void loadDoctorDetails() {

        oldDoctor = dd.findByDoctorId(doctorId);

        if (oldDoctor == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "Doctor record not found.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            dispose();
            return;
        }

        linkedUser = ud.findByUserId(oldDoctor.getUserId());

        if (linkedUser == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "Linked user account not found.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            dispose();
            return;
        }

        txtdocname.setText(oldDoctor.getDoctorName());
        txtcontactnumber.setText(oldDoctor.getContactNumber());
        txtconsultationfee.setText(
                String.valueOf(oldDoctor.getConsultationFee())
        );

        cmbspecialization.setSelectedItem(
                oldDoctor.getSpecialization()
        );

        // Stored format example: 09:00 AM -02:00 PM
        String hours = oldDoctor.getWorkingHours();

        if (hours != null && hours.contains("-")) {
            String[] parts = hours.split("-", 2);
            txtstarthours.setText(parts[0].trim());
            txtendhours.setText(parts[1].trim());
        } else {
            txtstarthours.setText("");
            txtendhours.setText("");
        }

        List<DayOfWeek> days = oldDoctor.getWorkingDays();

        chkmon.setSelected(days != null && days.contains(DayOfWeek.MONDAY));
        chktue.setSelected(days != null && days.contains(DayOfWeek.TUESDAY));
        chkwed.setSelected(days != null && days.contains(DayOfWeek.WEDNESDAY));
        chkthu.setSelected(days != null && days.contains(DayOfWeek.THURSDAY));
        chkfri.setSelected(days != null && days.contains(DayOfWeek.FRIDAY));
        chksat.setSelected(days != null && days.contains(DayOfWeek.SATURDAY));
        chksun.setSelected(days != null && days.contains(DayOfWeek.SUNDAY));

        rbnavailable.setSelected(oldDoctor.getAvaliabilityStatus());
        rbnunavailable.setSelected(!oldDoctor.getAvaliabilityStatus());
        rbnactive.setSelected(linkedUser.getIsActive());
        rbndeactive.setSelected(!linkedUser.getIsActive());
    }

